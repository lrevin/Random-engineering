import fs from 'node:fs';
import {createRequire} from 'node:module';
const root=new URL('../',import.meta.url),ts=createRequire(new URL('app/package.json',root))('typescript');
fs.mkdirSync(new URL('api/mysql/policy/',root),{recursive:true});
for(const name of ['stats','economy','quest-time','quests']){
 const source=fs.readFileSync(new URL('app/src/lib/'+name+'.ts',root),'utf8');
 const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText.replaceAll('"./quest-time"','"./quest-time.mjs"').replaceAll('"./stats"','"./stats.mjs"').replaceAll('"./economy"','"./economy.mjs"');
 fs.writeFileSync(new URL('api/mysql/policy/'+name+'.mjs',root),'// Generated by scripts/export-economy-policy.mjs; do not edit.\n'+code);
}
